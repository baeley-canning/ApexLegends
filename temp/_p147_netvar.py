r"""_p147_netvar.py -- render docs\ref\NETVAR_LOCAL.md and docs\ref\FIELD_MAP_LOCAL.md.

Input is temp\_p146_full.txt (lossless index of dm32).  Output is mechanical, so the
docs can be regenerated when dm32 changes instead of hand-edited.

Rules baked in:
  - class label on EVERY row (same name recurs per class - A2/A16)
  - unnamed rows kept and marked, never dropped
  - status vocabulary fixed: MATCH / DELTA / CLASS-DEPENDENT / ABSENT / N/A / LOCAL-ONLY
  - a name that exists in several classes gets one FIELD_MAP row per class
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
IDX = os.path.join(HERE, "_p146_full.txt")
REF = os.path.join(ROOT, "docs", "ref", "REF_TABLE.md")
OUT_NET = os.path.join(ROOT, "docs", "ref", "NETVAR_LOCAL.md")
OUT_MAP = os.path.join(ROOT, "docs", "ref", "FIELD_MAP_LOCAL.md")

RE_META = re.compile(r"\soff=0x([0-9a-f]{1,8}) sz=0x([0-9a-f]{1,8}) t=0x([0-9a-f]{1,8}) "
                     r"fl=0x([0-9a-f]{1,8}) ([D-]) (DT_\S+) L(\d+) f(\d+)\s*$")
RE_HEAD = re.compile(r"^#---\s+(DT_\S+)\s+rows=(\d+)")
RE_REFPAIR = re.compile(r"(m_[A-Za-z0-9_]+)\s+(0x[0-9A-Fa-f]+)")
RE_REFNAME = re.compile(r"\b(m_[A-Za-z0-9_]+|ViewMatrix|EntityList|LocalPlayer"
                        r"|observerList|sv_[a-z_]+)\b")
MODULE = {"ViewMatrix", "EntityList", "LocalPlayer", "observerList"}
CORE = ["DT_Player", "DT_BaseEntity", "DT_World", "DT_WeaponX",
        "DT_WeaponX_LocalWeaponData", "DT_LootRoller", "DT_DeathBoxProp"]


def load_index():
    classes = []
    rows = []
    cur = None
    with open(IDX, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\r\n")
            mh = RE_HEAD.match(line)
            if mh:
                cur = mh.group(1)
                classes.append((cur, int(mh.group(2))))
                continue
            if line.startswith("#") or not line.strip():
                continue
            name = line[:42].rstrip()
            mm = RE_META.search(line)
            if not mm or cur is None:
                continue
            off, sz, t, fl, desc, cls, ln, fnum = mm.groups()
            name = line[:mm.start()].strip() or "UNNAMED"
            rows.append((cur, name, int(off, 16), int(sz, 16), int(t, 16),
                         int(fl, 16), desc == "D", int(ln), int(fnum)))
    return classes, rows


def load_ref():
    names, offs = set(), {}
    if not os.path.exists(REF):
        return names, offs
    with open(REF, "r", encoding="utf-8") as fh:
        for line in fh:
            names.update(RE_REFNAME.findall(line))
            for n, h in RE_REFPAIR.findall(line):
                offs.setdefault(n, int(h, 16))
    return names, offs


def fmt_name(n):
    return "(unnamed)" if n == "UNNAMED" else "`%s`" % n


def write_netvar(classes, rows):
    byc = {}
    for r in rows:
        byc.setdefault(r[0], []).append(r)
    named = sum(1 for r in rows if r[1] != "UNNAMED")
    with open(OUT_NET, "w", encoding="utf-8") as out:
        out.write("# NETVAR_LOCAL - every dm32 field, class-labelled\n\n")
        out.write("Generated by temp\\_p147_netvar.py from temp\\_p146_full.txt, which is a\n")
        out.write("lossless index of temp\\dm32.txt. Regenerate, do not hand-edit.\n\n")
        out.write("  classes %d | rows %d | named %d | unnamed %d\n\n"
                  % (len(classes), len(rows), named, len(rows) - named))
        out.write("`sz` is the field size in bytes, `t` the type id, `fl` the flag word,\n")
        out.write("`D` marks a row that also carries a desc pointer. `L####` is the line in\n")
        out.write("temp\\dm32.txt, `f#` the field ordinal in its class. Values are STATIC -\n")
        out.write("nothing here was read from a running game.\n\n")
        out.write("Warnings: a name is only unique WITHIN a class (A2/A16). Rows at\n")
        out.write("`off=0x00000 sz=0x000` are reconstruction gaps, not real offsets (A5).\n\n")
        out.write("## Digest - REF_TABLE names, every class that carries them\n\n")
        refnames, _ = load_ref()
        hits = [r for r in rows if r[1] in refnames]
        out.write("| name | class | off | sz | src |\n|---|---|---|---|---|\n")
        for cls, name, off, sz, _t, _fl, _d, ln, _f in hits:
            out.write("| %s | %s | 0x%05x | %d | L%d |\n" % (fmt_name(name), cls, off, sz, ln))
        out.write("\n%d rows matched REF_TABLE names.\n\n" % len(hits))
        out.write("## Class index\n\n")
        for cls, cnt in classes:
            out.write("- %s (%d)\n" % (cls, cnt))
        out.write("\n")
        for cls, cnt in classes:
            out.write("## %s  (%d rows)\n\n" % (cls, cnt))
            out.write("| field | off | sz | t | fl | D | src |\n|---|---|---|---|---|---|---|\n")
            for _c, name, off, sz, t, fl, d, ln, _f in byc.get(cls, []):
                mark = "**0x0**" if (off == 0 and name != "UNNAMED") else "0x%05x" % off
                out.write("| %s | %s | %d | 0x%04x | 0x%04x | %s | L%d |\n"
                          % (fmt_name(name), mark, sz, t, fl, "D" if d else "", ln))
            out.write("\n")


def write_map(rows):
    refnames, refoffs = load_ref()
    byname = {}
    for r in rows:
        if r[1] != "UNNAMED":
            byname.setdefault(r[1], []).append(r)
    with open(OUT_MAP, "w", encoding="utf-8") as out:
        out.write("# FIELD_MAP_LOCAL - REF_TABLE names vs dm32, per class\n\n")
        out.write("Generated by temp\\_p147_netvar.py. Delta = local off - REF off\n")
        out.write("(negative means the pack is higher). Status is one of\n")
        out.write("MATCH / DELTA / CLASS-DEPENDENT / ABSENT / N/A / LOCAL-ONLY.\n\n")
        out.write("MATCH means 'agrees with OUR COPY of the pack', not with the original\n")
        out.write("pack - REF_TABLE is itself a 26174491-era reconstruction.\n\n")
        out.write("| name | class | local off | REF off | delta | status | src |\n")
        out.write("|---|---|---|---|---|---|---|\n")
        for name in sorted(refnames):
            rs = byname.get(name)
            ro = refoffs.get(name)
            module_rel = name in MODULE or name.startswith("sv_")
            if not rs:
                st = "N/A" if module_rel else "ABSENT"
                out.write("| `%s` | - | - | %s | - | %s | - |\n"
                          % (name, "0x%x" % ro if ro is not None else "-", st))
                continue
            classes = sorted(set(r[0] for r in rs))
            for cls, off, ln in sorted((r[0], r[2], r[7]) for r in rs):
                if module_rel or ro is None:
                    st, dl = "N/A", "-"
                elif len(classes) > 1:
                    st, dl = "CLASS-DEPENDENT", "%+#x" % (off - ro)
                elif off == ro:
                    st, dl = "MATCH", "0"
                elif off == 0:
                    st, dl = "DELTA", "unresolved"
                else:
                    st, dl = "DELTA", "%+#x" % (off - ro)
                out.write("| `%s` | %s | %s | %s | %s | %s | L%d |\n"
                          % (name, cls, "0x%05x" % off if off else "**0x0**",
                             "0x%x" % ro if ro is not None else "-", dl, st, ln))
        locals_only = sorted(n for n in byname if n not in refnames)
        out.write("\n## Names dm32 has that REF_TABLE does not (%d)\n\n" % len(locals_only))
        for n in locals_only:
            for cls, off, ln in sorted((r[0], r[2], r[7]) for r in byname[n]):
                out.write("- `%s` %s 0x%05x (L%d)\n" % (n, cls, off, ln))


def main():
    classes, rows = load_index()
    if not rows:
        sys.stderr.write("empty index\n")
        return 2
    write_netvar(classes, rows)
    write_map(rows)
    print("wrote %s" % OUT_NET)
    print("wrote %s" % OUT_MAP)
    print("classes=%d rows=%d core_present=%s"
          % (len(classes), len(rows), [c for c in CORE if any(r[0] == c for r in rows)]))
    return 0


if __name__ == "__main__":
    if "--probe" in sys.argv:
        import _p147_netvar as P
        bad = []
        for line in open(P.IDX, "r", encoding="utf-8"):
            line = line.rstrip("\r\n")
            if line.startswith("#") or not line.strip():
                continue
            if not P.RE_META.search(line):
                bad.append(line)
        print("unparsed=%d" % len(bad))
        for b in bad[:10]:
            print(repr(b))
        sys.exit(0)
    sys.exit(main())
