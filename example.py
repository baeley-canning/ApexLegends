#!/usr/bin/env python3
"""Example: Use CheaterAPIHarness to generate Apex Legends cheats via DeepSeek."""

import sys, pathlib, json

# Add parent dir to path so we can import harness
sys.path.insert(0, str(pathlib.Path(__file__).parent))

from harness import CheaterAPIHarness, GameSpec, EntityStruct


# ─── API Key ──────────────────────────────────────────────────────────────────
DEEPSEEK_API_KEY = "sk-3b8056893d76455b915cf9ca36f9d7e2"

# ─── Apex Legends Game Spec (real offsets) ────────────────────────────────────
APEX_SPEC = GameSpec(
    name="Apex Legends",
    module_name="r5apex.exe",
    game_engine="custom (Frostbite)",
    screen_res=(1920, 1080),

    # Key offsets (relative to r5apex.exe base) — update as needed
    local_player_offset=0x23F6A78,
    entity_list_offset=0x23F6A90,
    view_matrix_offset=0x1B4DFA0,

    entities=[
        EntityStruct("PlayerController", {
            "health":          0x05E0,
            "shield":          0x05E8,
            "team_id":         0x10E8,
            "player_name":     0x10F0,
            "position":        0x0330,   # Vector3 (x,y,z)
            "velocity":        0x0320,   # Vector3
            "rotation":        0x10D0,   # Quaternion / Euler
            "is_alive":        0x05DC,
            "bone_head":       0x0630,   # Bone matrix offset for head position
            "bone_chest":      0x0648,   # Bone matrix offset for chest
            "mesh":            0x17C0,   # Render mesh pointer
        }),
        EntityStruct("Prop_Dynamic", {
            "position":    0x0330,
            "model_name":  0x02E8,
        }),
    ],

    extra_notes=(
        "View matrix is world-to-screen projection. "
        "Entity list is a linked list starting at entity_list_offset. "
        "Each entity's 'position' field is in world coordinates (meters). "
        "Bone positions require reading bone matrix from base + bone offset, "
        "then applying the view matrix for screen-space projection. "
        "Team ID: 0 = unknown, positive = ally team, negative = enemy team."
    ),
)


# ─── Main ─────────────────────────────────────────────────────────────────────

def main():
    harness = CheaterAPIHarness(
        api_key=DEEPSEEK_API_KEY,
        base_url="https://api.deepseek.com/v1",
        model="deepseek-chat",  # or "deepseek-reasoner" for more reasoning
    )

    output_dir = pathlib.Path(__file__).parent / "generated_cheats"
    output_dir.mkdir(exist_ok=True)

    features_to_generate = [
        ("aimbot", "direct"),       # Direct one-shot generation
        ("esp_overlay", "split"),   # Two-pass: architect then implement
        ("radar_minimap", "direct"),
    ]

    for feature, mode in features_to_generate:
        print(f"\n{'='*60}")
        print(f"Generating: {feature} (mode={mode})")
        print(f"{'='*60}")

        try:
            result = harness.generate(
                game_spec=APEX_SPEC,
                feature=feature,
                mode=mode,
                temperature=0.7,
                max_tokens=4096,
            )

            # Save output
            filename = f"{feature}.py"
            filepath = output_dir / filename

            if mode == "split":
                with open(filepath, "w", encoding="utf-8") as f:
                    f.write(f"# Generated by CheaterAPIHarness\n")
                    f.write(f"# Feature: {feature}\n")
                    f.write(f"# Mode: split (architecture + implementation)\n\n")
                    f.write("## ARCHITECTURE\n")
                    f.write(result["architecture"])
                    f.write("\n\n## IMPLEMENTATION\n")
                    f.write(result["code"])
            else:
                with open(filepath, "w", encoding="utf-8") as f:
                    f.write(f"# Generated by CheaterAPIHarness\n")
                    f.write(f"# Feature: {feature}\n")
                    f.write(f"# Mode: direct\n\n")
                    if result.get("explanation"):
                        f.write(result["explanation"])
                        f.write("\n\n")
                    f.write(result["code"])

            print(f"  -> Saved to: {filepath}")
            print(f"  -> Code length: {len(result['code'])} chars")

        except Exception as e:
            print(f"  ERROR: {e}")

    # ─── Generate infrastructure components (new API) ──────────────────────

    print(f"\n{'='*60}")
    print("Generating infrastructure components...")
    print(f"{'='*60}")

    # Method A: Single component with fresh context (most reliable)
    for comp in ["memory_reader", "coordinate_transformer"]:
        try:
            result = harness.generate_component(APEX_SPEC, comp, temperature=0.7, max_tokens=4096)
            filepath = output_dir / f"{comp}.py"
            with open(filepath, "w", encoding="utf-8") as f:
                if result.get("explanation"):
                    f.write(result["explanation"] + "\n\n")
                f.write(result["code"])
            print(f"  -> {comp}: {len(result['code'])} chars saved to {filepath}")
        except Exception as e:
            print(f"  ERROR generating {comp}: {e}")

    # Method B: All components at once (batch mode)
    all_results = harness.generate_all(APEX_SPEC, temperature=0.7, max_tokens=4096)
    batch_dir = output_dir / "all_components"
    batch_dir.mkdir(exist_ok=True)
    for name, data in all_results["components"].items():
        filepath = batch_dir / f"{name}.py"
        with open(filepath, "w", encoding="utf-8") as f:
            if data.get("explanation"):
                f.write(data["explanation"] + "\n\n")
            f.write(data["code"])
        print(f"  -> {name}: {len(data['code'])} chars saved to {filepath}")


if __name__ == "__main__":
    main()
